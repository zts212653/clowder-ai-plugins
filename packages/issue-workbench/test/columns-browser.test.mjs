import { expandSection } from './helpers/expand-section.mjs';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { test } from 'node:test';
import { chromium } from 'playwright';

const repo = fileURLToPath(new URL('../../../', import.meta.url));
test('packed columns: drag, keyboard, persistence, container resize and retained drafts', { timeout: 90000 }, async t => {
  const directory = await mkdtemp(join(tmpdir(), 'issue-columns-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const [pack] = JSON.parse(execFileSync(process.execPath,
    ['scripts/pack-publish-artifact.mjs', 'packages/issue-workbench', directory], { cwd: repo, encoding: 'utf8' }));
  execFileSync('tar', ['-xzf', join(directory, pack.filename), '-C', directory]);
  const { coordinationPreview, fixtureBindings } = await import(pathToFileURL(join(directory, 'package/dist/coordination-host.mjs')).href);
  const server = coordinationPreview({ dataRoot: join(directory, 'data'), dist: join(directory, 'package/dist'), bindings: fixtureBindings() });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(4000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:' + server.address().port);
  const queue = page.getByRole('complementary', { name: '聚合问题队列' });
  const reading = page.getByRole('region', { name: '问题正文', exact: true });
  const notes = page.getByRole('region', { name: '本仓研判', exact: true });
  const left = page.getByRole('separator', { name: '调整队列宽度', exact: true });
  const right = page.getByRole('separator', { name: '调整研判宽度', exact: true });
  await reading.waitFor();
  await left.waitFor();
  const width = async locator => (await locator.boundingBox()).width;
  const initial = { queue: await width(queue), notes: await width(notes) };
  const drag = async (separator, delta) => {
    const box = await separator.boundingBox();
    const x = box.x + box.width / 2, y = box.y + Math.min(box.height / 2, 200);
    await page.mouse.move(x, y); await page.mouse.down();
    await page.mouse.move(x + delta, y, { steps: 8 }); await page.mouse.up();
  };
  await drag(left, 90);
  assert.ok(Math.abs(await width(queue) - initial.queue - 90) < 2);
  assert.ok(Math.abs(await width(notes) - initial.notes) < 2, 'left separator leaves the far pane unchanged');
  await drag(right, -100);
  assert.ok(Math.abs(await width(notes) - initial.notes - 100) < 2);
  await right.focus(); await page.keyboard.press('ArrowRight');
  assert.ok(Math.abs(await width(notes) - initial.notes - 80) < 2, 'right arrow moves the right separator to the right');
  const changed = { queue: await width(queue), notes: await width(notes) };
  await page.reload(); await reading.waitFor();
  assert.ok(Math.abs(await width(queue) - changed.queue) < 2);
  assert.ok(Math.abs(await width(notes) - changed.notes) < 2);
  await expandSection(page, '补充分析（可选）');
  await page.getByLabel('分析备注', { exact: true }).fill('调整布局保留的草稿');
  // A narrow embedded panel must adapt even when the outer browser stays wide.
  const container = async value => {
    await page.locator('#app').evaluate((el, size) => { el.style.width = size; }, value);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  };
  await container('1120px');
  assert.ok(await width(reading) >= 359 && await width(notes) >= 299 && await width(queue) >= 219);
  await container('100%');
  assert.ok(Math.abs(await width(queue) - changed.queue) < 2, 'temporary clamping preserves the preferred widths');
  assert.ok(Math.abs(await width(notes) - changed.notes) < 2);
  await container('1050px');
  assert.equal(await right.isVisible(), false);
  await left.focus(); await page.keyboard.press('End');
  assert.ok(await width(reading) >= 359, 'drag/keyboard cannot crush the reading pane');
  await page.getByRole('button', { name: '研判', exact: true }).click();
  assert.equal(await page.getByLabel('分析备注', { exact: true }).inputValue(), '调整布局保留的草稿');
  await container('600px');
  assert.equal(await left.isVisible(), false);
  await page.getByRole('button', { name: '队列', exact: true }).click();
  assert.equal(await queue.isVisible(), true);
  await page.getByRole('button', { name: '研判', exact: true }).click();
  assert.equal(await page.getByLabel('分析备注', { exact: true }).inputValue(), '调整布局保留的草稿');
  assert.ok(await page.locator('#app').evaluate(el => el.scrollWidth <= el.clientWidth));
  await container('100%');
  await right.focus(); await page.keyboard.press('End');
  assert.ok(await width(notes) >= 299 && await width(reading) >= 359);
  await drag(left, 1600);
  assert.ok(await width(reading) >= 359 && await width(notes) >= 299);
  await left.focus(); await page.keyboard.press('Enter');
  assert.ok(Math.abs(await width(queue) - initial.queue) < 2);
  assert.ok(Math.abs(await width(notes) - initial.notes) < 2);
  await drag(left, 80); await left.dblclick();
  assert.ok(Math.abs(await width(queue) - initial.queue) < 2);
  await mkdir('artifacts/columns-2026-10-21', { recursive: true });
  await drag(right, -120);
  await page.screenshot({ path: 'artifacts/columns-2026-10-21/desktop.png' });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: 'artifacts/columns-2026-10-21/dark.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '研判', exact: true }).click();
  assert.equal(await page.getByLabel('分析备注', { exact: true }).inputValue(), '调整布局保留的草稿');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const save = await page.getByRole('button', { name: '保存分析', exact: true }).boundingBox();
  assert.ok(save && save.y >= 0 && save.y + save.height <= 844);
  await page.screenshot({ path: 'artifacts/columns-2026-10-21/mobile.png' });
  await page.getByRole('button', { name: '保存分析', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('button[type="submit"]')?.disabled);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => localStorage.setItem('issue-workbench:columns:v1', '{broken'));
  await page.reload(); await left.waitFor();
  assert.ok(Math.abs(await width(queue) - initial.queue) < 2, 'invalid stored widths restore defaults');
  await page.evaluate(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Blocked', 'SecurityError'); } }));
  await drag(left, 40);
  assert.ok(Math.abs(await width(queue) - initial.queue - 40) < 2, 'unavailable storage does not block resizing');
  assert.deepEqual(errors, []);
});
