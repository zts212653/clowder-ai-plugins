import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { chromium } from 'playwright';
import { preview } from '../scripts/preview.mjs';
const root = fileURLToPath(new URL('../../../',import.meta.url));
test('packed browser: read, page comments, save, reload, protect unsaved edits, narrow layout', { timeout: 90000 }, async t => {
  const dir=mkdtempSync(join(tmpdir(),'issue-browser-artifact-'));
  t.after(()=>rmSync(dir,{recursive:true,force:true}));
  const [pack]=JSON.parse(execFileSync(process.execPath,['scripts/pack-publish-artifact.mjs','packages/issue-workbench',dir],{cwd:root,encoding:'utf8'}));
  execFileSync('tar',['-xzf',join(dir,pack.filename),'-C',dir]);
  const server=preview(join(dir,'package/dist'));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>new Promise(resolve=>{ server.closeAllConnections(); server.close(resolve); }));
  const browser=await chromium.launch({headless:true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE} : {})}); t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:1000}}); const errors=[]; const external=[];
  page.on('pageerror', e=>errors.push(e.message));
  await page.route('**/*', route=>{ if (!route.request().url().startsWith('http://127.0.0.1:')) {external.push(route.request().url());return route.abort();} return route.continue();});
  await page.goto('http://127.0.0.1:'+server.address().port);
  await page.getByText('阅读与验证',{exact:true}).waitFor();
  assert.match(await page.locator('body').textContent(),/25 \/ 37/);
  await page.getByRole('button',{name:'加载更多评论',exact:true}).click();
  await page.getByText('合成讨论 37',{exact:true}).waitFor();
  await page.getByRole('tab',{name:'解决方案',exact:true}).click();
  await page.getByRole('textbox',{name:'解决方案',exact:true}).fill('可恢复的方案');
  await page.getByRole('button',{name:'保存方案',exact:true}).click();
  await page.reload();
  await page.getByRole('tab',{name:'解决方案',exact:true}).click();
  assert.equal(await page.getByRole('textbox',{name:'解决方案',exact:true}).inputValue(),'可恢复的方案');
  await page.getByRole('textbox',{name:'解决方案',exact:true}).fill('未保存修改');
  await page.getByRole('button',{name:'停用体验插件',exact:true}).click();
  await page.getByRole('button',{name:'继续编辑',exact:true}).click();
  assert.equal(await page.getByRole('textbox',{name:'解决方案',exact:true}).inputValue(),'未保存修改');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:/改善离线阅读体验/}).click();
  await page.getByRole('textbox',{name:'解决方案',exact:true}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  mkdirSync('artifacts',{recursive:true});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'artifacts/packed-mobile.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'artifacts/packed-desktop.png',fullPage:true,animations:'disabled'});
  assert.deepEqual(errors,[]); assert.deepEqual(external,[]);
});
