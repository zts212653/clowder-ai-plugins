import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import test from 'node:test';
import { Receiver } from '../src/engine.mjs';
import { git } from '../src/process.mjs';
import { versionRepositories } from './version-fixtures.mjs';

test('version: tag update fully preserves internal README, strictly updates core, uses one PR and recovers without Issues', async () => {
  const f = await versionRepositories();
  let receiver = new Receiver(f.config);
  await receiver.adopt(f.u0, f.i0);
  const tags = await receiver.tags();
  assert.ok(tags.some((tag) => tag.name === 'v2.0.0' && tag.commit === f.u1));
  await receiver.selectTag('v2.0.0');
  await receiver.start();
  await receiver.prepare();
  let state = await receiver.status();
  assert.deepEqual(state.issues, {});
  assert.equal(state.active.issues.length, 0);
  assert.equal(state.queue.length, 1);
  const head = state.active.candidate;
  assert.equal(await git(receiver.git.directory, ['show', `${head}:core.txt`]), 'release two');
  assert.equal(await git(receiver.git.directory, ['show', `${head}:internal-docs/guide.md`]), '内部独立说明');
  assert.equal(await git(receiver.git.directory, ['show', `${head}:OWNED.md`]), '内部维护说明');
  assert.equal(await git(receiver.git.directory, ['show', `${head}:README.md`]), '介绍\n\n运行说明\n\n内部联系说明');
  assert.equal(await receiver.git.isAncestor(f.u1, head), false);
  assert.match(state.templates.title, /v2\.0\.0/);
  assert.doesNotMatch(state.templates.body, /Fixes #71/);
  await receiver.linkPr('https://codehub.example/core/pull/501');
  const accepted = await f.merge(state.active);
  receiver = new Receiver(f.config);
  await git(f.source, ['tag', '-f', 'v2.0.0', f.u0]);
  await assert.rejects(() => receiver.recover(), { code: 'TAG_MOVED' });
  assert.equal((await receiver.status()).accepted.upstream, f.u0);
  await git(f.source, ['update-ref', 'refs/tags/v2.0.0', state.active.frozenTag.object]);
  await receiver.recover();
  state = await receiver.status();
  assert.equal(state.active, undefined);
  assert.equal(state.accepted.tag, 'v2.0.0');
  assert.equal(state.accepted.internal, accepted);
  assert.equal(state.deliveries[0].status, 'COMPLETE');
  assert.deepEqual(state.issues, {});
  await assert.rejects(() => receiver.selectTag('v1.0.0'), { code: 'VERSION_NOT_FORWARD' });
  await writeFile(join(f.source, 'core.txt'), 'release three');
  await git(f.source, ['add', '.']);
  await git(f.source, ['commit', '-m', 'release three']);
  await git(f.source, ['tag', 'v3.0.0']);
  await writeFile(join(f.review, 'internal-docs', 'guide.md'), '内部后续定制');
  await git(f.review, ['add', '.']);
  await git(f.review, ['commit', '-m', 'later customization']);
  await git(f.review, ['push', 'origin', 'main']);
  await receiver.selectTag('v3.0.0');
  await receiver.start();
  await receiver.prepare();
  await receiver.linkPr('https://codehub.example/core/pull/502');
  await f.merge((await receiver.status()).active);
  await receiver.recover();
  assert.equal((await receiver.status()).accepted.tag, 'v3.0.0');
  assert.equal((await receiver.status()).deliveries.length, 2);
});

test('version: unapproved baseline changes and tag rollback are rejected', async () => {
  const f = await versionRepositories();
  await writeFile(join(f.review, 'core.txt'), 'unapproved internal core change');
  await git(f.review, ['add', '.']);
  await git(f.review, ['commit', '-m', 'unapproved customization']);
  await git(f.review, ['push', 'origin', 'main']);
  const bad = await git(f.review, ['rev-parse', 'HEAD']);
  await assert.rejects(() => new Receiver(f.config).adopt(f.u0, bad), { code: 'UNAPPROVED_DIFFERENCE' });
  const other = await versionRepositories();
  const receiver = new Receiver(other.config);
  await receiver.adopt(other.u0, other.i0);
  await assert.rejects(() => receiver.selectTag('v1.0.0'), { code: 'NO_VERSION_UPDATE' });
});
