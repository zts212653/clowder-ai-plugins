import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const evidence=process.env.WECHAT_EVIDENCE_DIR ?? '/tmp/wechat-alpha6-chooser';
await mkdir(evidence,{recursive:true});
const {chromium}=await import(process.env.WECHAT_PLAYWRIGHT_MODULE ?? 'playwright');
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1280,height:1000}}),reads=[],errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('request',r=>{if(r.url().endsWith('/fixture-control')){try{if(r.postDataJSON()?.action==='chats')reads.push(r.postDataJSON());}catch{}}});
 await page.goto('http://127.0.0.1:5188/');
 const f=page.frameLocator('#panel');
 await f.getByLabel('我了解将准备基于 Agent WeChat 2.4.1 的 Clowder 通讯录修复构建；组件会连接微信服务器，登录可能同步更广范围消息到本机。猫只处理我另行授权的会话。').check();
 await f.getByRole('button',{name:'准备账号连接组件',exact:true}).click();
 await f.getByRole('button',{name:'微信扫码登录',exact:true}).click();
 await f.getByLabel('值班猫',{exact:true}).selectOption('review-cat');
 await page.waitForTimeout(200);
 assert.equal(reads.length,0,'recipient directory must be loaded only after opening the chooser');
 const picker=f.getByRole('combobox',{name:'指定好友或群',exact:true});
 await picker.click();
 const list=f.getByRole('listbox',{name:'好友与群候选'});
 await list.getByRole('option').first().waitFor();
 assert.equal(await list.getByRole('option').count(),20);
 await f.getByRole('button',{name:'加载更多',exact:true}).click();
 await list.getByRole('option').nth(39).waitFor();
 assert.equal(await list.getByRole('option').count(),40);
 await page.screenshot({path:`${evidence}/chooser-open.png`,fullPage:true});
 await f.getByRole('searchbox',{name:'搜索好友或群'}).press('Escape');
 assert.equal(await list.isVisible(),false);
 await picker.click();
 await f.getByRole('tab',{name:'群',exact:true}).click();
 await f.getByRole('searchbox',{name:'搜索好友或群'}).fill('周书');
 await list.getByRole('option',{name:/周末读书群/}).waitFor();
 assert.equal(await f.getByRole('tab',{name:'群',exact:true}).innerText(),'群 1');
 await page.screenshot({path:`${evidence}/chooser-group-search.png`,fullPage:true});
 await list.getByRole('option',{name:/周末读书群/}).click();
 await f.getByLabel('人设与交流边界',{exact:true}).fill('自然友好，只聊读书');
 await f.getByLabel('这次要聊什么',{exact:true}).fill('周末阅读');
 const consent=f.getByLabel('我允许所选会话的文字交给上述模型服务，并允许猫在约定范围内直接发送。家庭记忆、文件、命令、支付、外链和附件访问均不开放。');
 await consent.check();
 await page.waitForTimeout(3500);
 assert.equal(await consent.isChecked(),true,'normal status polling must preserve the same authorization scope');
 assert.equal(await f.getByRole('button',{name:'开启代聊',exact:true}).isEnabled(),true);
 await f.getByLabel('值班猫',{exact:true}).selectOption('review-cat-unavailable');
 await f.getByText('这只猫的受限模型服务当前不可用。',{exact:false}).waitFor();
 assert.equal(await consent.isChecked(),false);
 assert.equal(await consent.isVisible(),false);
 assert.equal(await f.getByRole('button',{name:'开启代聊',exact:true}).isEnabled(),true);
 await f.getByRole('button',{name:'开启代聊',exact:true}).click();
 await f.getByText('所选猫的受限模型尚未就绪，请等待核验或换一只猫。',{exact:true}).waitFor();
 await f.getByLabel('值班猫',{exact:true}).selectOption('review-cat');
 await consent.check();
 await f.getByRole('button',{name:'开启代聊',exact:true}).click();
 await f.getByText('正在核对当前微信通讯录，请稍后重试开启代聊。',{exact:true}).waitFor();
 assert.equal(await consent.isChecked(),true);
 assert.match(await picker.innerText(),/周末读书群/);
 await page.waitForTimeout(3500);
 assert.equal(await consent.isChecked(),true);
 await f.getByRole('button',{name:'开启代聊',exact:true}).click();
 await f.getByText('猫代聊中 · 可随时接管',{exact:true}).waitFor();
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,boundary:'isolated model and account',reads:reads.length}));
}finally{await browser.close();}
