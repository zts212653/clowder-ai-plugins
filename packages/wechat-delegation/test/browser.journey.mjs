import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.WECHAT_PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({ headless: true });
const evidence = process.env.WECHAT_EVIDENCE_DIR ?? '/tmp/wechat-delegation-browser';
await mkdir(evidence, { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5188/');
  const frame = page.frameLocator('#panel');
  await frame.getByRole('heading', { name: '连接微信账号', exact: true }).waitFor();
  assert.equal(await frame.getByRole('heading', { name: '配置代聊会话', exact: true }).isVisible(), false);
  assert.equal(await frame.getByRole('heading', { name: '代聊会话', exact: true }).isVisible(), false);
  assert.equal(await frame.getByRole('heading', { name: '发送记录', exact: true }).isVisible(), false);
  assert.equal(await frame.getByRole('button', { name: '暂停全部代聊', exact: true }).isEnabled(), true);
  const typography = await frame.getByRole('heading', { name: '微信代聊', exact: true }).evaluate(node => getComputedStyle(node).fontSize);
  assert.equal(typography, '16px');
  await page.screenshot({ path: `${evidence}/unconnected.png`, fullPage: true });
  await frame.getByLabel('我了解将准备第三方 Agent WeChat 2.4.1；登录可能同步更广范围消息到本机。猫只处理我另行授权的会话。').check();
  await frame.getByRole('button', { name: '准备账号连接组件', exact: true }).click();
  await frame.getByRole('button', { name: '微信扫码登录', exact: true }).click();
  await frame.getByRole('heading', { name: '配置代聊会话', exact: true }).waitFor();
  await page.screenshot({ path: `${evidence}/configure.png`, fullPage: true });
  await frame.getByLabel('指定好友或群', { exact: true }).selectOption(JSON.stringify({ id: 'preview-room@chatroom', kind: 'group' }));
  await frame.getByLabel('值班猫', { exact: true }).selectOption('review-cat');
  await frame.getByLabel('人设与交流边界', { exact: true }).fill('像熟人一样自然友好，只聊读书');
  await frame.getByLabel('这次要聊什么', { exact: true }).fill('邀请大家周末一起读科幻小说');
  await frame.getByText('实际模型：模拟模型；客户端：隔离测试。', { exact: false }).waitFor();
  await frame.getByLabel('我允许所选会话的文字交给上述模型服务，并允许猫在约定范围内直接发送。家庭记忆、文件、命令、支付、外链和附件访问均不开放。').check();
  await frame.getByRole('button', { name: '开启代聊', exact: true }).click();
  await frame.getByText('猫代聊中 · 可随时接管', { exact: true }).waitFor();
  assert.equal(await frame.getByRole('heading', { name: '配置代聊会话', exact: true }).isVisible(), false);
  await page.screenshot({ path: `${evidence}/active.png`, fullPage: true });
  await frame.getByRole('button', { name: '立即主动开口', exact: true }).click();
  await frame.getByText('发送结果未知 · 不会自动重发', { exact: false }).waitFor();
  await frame.getByRole('button', { name: '我来聊', exact: true }).click();
  await frame.getByText('本人接管中 · 后续代聊已停止', { exact: true }).waitFor();
  assert.equal(await frame.getByRole('button', { name: '立即主动开口', exact: true }).isDisabled(), true);
  await frame.getByText('在途消息待核对', { exact: true }).waitFor();
  await frame.getByRole('heading', { name: '代聊会话', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${evidence}/desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await frame.getByRole('button', { name: '暂停全部代聊', exact: true }).click();
  await frame.getByText('全部代聊已暂停', { exact: true }).waitFor();
  await frame.getByRole('heading', { name: '代聊会话', exact: true }).scrollIntoViewIfNeeded();
  const metrics = await frame.locator('body').evaluate(node => ({ scroll: node.scrollWidth, width: document.documentElement.clientWidth }));
  assert.ok(metrics.scroll <= metrics.width + 1, `mobile overflow: ${JSON.stringify(metrics)}`);
  await page.screenshot({ path: `${evidence}/mobile.png`, fullPage: true });
  const light = await frame.locator('html').evaluate(node => getComputedStyle(node).backgroundColor);
  await page.emulateMedia({ colorScheme: 'dark' });
  const dark = await frame.locator('html').evaluate(node => getComputedStyle(node).backgroundColor);
  assert.notEqual(dark, light, 'dark scheme must change the panel surface');
  await page.screenshot({ path: `${evidence}/mobile-dark.png`, fullPage: true });
  assert.deepEqual(errors, []);
  process.stdout.write(JSON.stringify({ passed: true, viewports: ['1280x900', '390x844'], evidence, boundary: 'isolated fake daemon/model only' }) + '\n');
  await page.close();
} finally { await browser.close(); }
